/**
 * ЛОГІКА НАБІГУ ХИЖАКА — окремо від компонентів.
 *
 * Винесено з `RaidRun.tsx` навмисно: файл із компонентами має експортувати
 * ЛИШЕ компоненти, інакше Fast Refresh не працює (React перезавантажує весь
 * файл, втрачаючи стан). Тому умови й маршрут живуть тут, а компоненти
 * (`RaidRun`, `MobileRaid`) імпортують звідси.
 */
import { PREDATORS, ZONES } from '../../game/config';
import type { GameEvent } from '../../game/types';

/**
 * Чи показувати набіг цієї події.
 *
 * Показуємо ЗА ПОДІЄЮ, а не за станом двору. Було: умова вимагала наявної
 * жертви в дворі або `delta ≠ 0`. Але `farm` — це стан ПІСЛЯ ходу, де
 * вкраденого вже немає, тож набіг не показувався саме в момент крадіжки.
 * Сама подія `loss` із `raider` — вже доведений напад.
 *
 * `kind: 'raid'` — окремий випадок «забирав, але нічого не було»: хижак теж
 * пробігає, показуючи, що загроза була.
 */
export function shouldShowRaid(events: readonly GameEvent[]): GameEvent | undefined {
  return events.find(
    (item) => item.raider && (item.kind === 'loss' || item.kind === 'raid'),
  );
}

/**
 * МАРШРУТ НАБІГУ (ПК) — хижак обходить СВОЇ жертви по черзі.
 *
 * Лисиця краде качок і кіз, ведмідь — свиней і коней. Тому вона має пройти
 * саме цими дворами: спершу перший, потім другий, і лише тоді тікати.
 *
 * Координати беруться з ZONES (та сама розкладка, що для загонів), тож
 * маршрут автоматично збігається з картою — за переносу загону в редакторі
 * нічого правити не треба.
 */
export function raidPath(raider: 'fox' | 'bear'): { x: number; y: number }[] {
  const stops = PREDATORS[raider].steals.map((key) => {
    const zone = ZONES[key];
    // Точка зупинки — центр загону: там хижак «стоїть над» тваринами.
    return { x: zone.x + zone.w / 2, y: zone.y + zone.h / 2 };
  });
  // Втеча: за правий край карти, за межі поля (там ліс).
  return [...stops, { x: -12, y: stops[0]?.y ?? 20 }];
}

/**
 * ПАРАМЕТРИ ХОДИ для спрайта хижака.
 *
 * Назви змінних — ті самі, що дає `motionFor()` для тварин у загонах:
 *   · `--walk-dur` — час одного повного циклу кадрів;
 *   · `--delay`     — зсув фази (негативний, щоб стартувати посеред циклу);
 *   · `--waddle`    — нахил у такт із кроком;
 *   · `--flip`      — напрямок: хижак біжить уліво, у ліс, тож -1.
 *
 * Темп 0.4 с на цикл — швидше за тварин у дворі (там 1–3 с): хижак БІЖИТЬ,
 * а не пасеться. Шість кадрів за 0.4 с дають плавний біг, не мерехтіння.
 */
export function raidWalkVars(): Record<string, string> {
  return {
    ['--walk-dur' as string]: '0.4s',
    ['--delay' as string]: '-0.15s',
    ['--waddle' as string]: '3deg',
    ['--flip' as string]: '-1',
  };
}
