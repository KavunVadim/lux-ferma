import { WALK_STYLE } from '../../game/config';
import type { HerdKey } from '../../game/types';

/**
 * Детермінована «випадковість» для анімацій спрайтів.
 *
 * Тварини мають рухатися по-різному (пастися, ходити, підстрибувати) і не
 * синхронно. Справжній `Math.random` тут не годиться: кожен рендер давав би
 * нові значення, і спрайт смикався б на місці. Тому параметри рахуються
 * хешем від стабільного ключа (вид тварини + її номер у загоні).
 */
/**
 * Вид руху спрайта. Лишився тільки `wander`: тварини стоять на місцях, а
 * «пасіння»/«відпочинок»/«стрибки» (graze/rest/hop) прибрано — вони або
 * виглядали як підскакування, або робили тварину нерухомою.
 */
export type MotionKind = 'wander';
export interface Motion {
  kind: MotionKind;
  /** CSS-змінні для кадрів анімації. */
  vars: Record<string, string>;
}

/** Цілочисельний хеш (xorshift) → 0..1. Стабільний для одного входу. */
export function noise(seed: number): number {
  let x = (seed * 2654435761) % 2147483647;
  if (x <= 0) x += 2147483646;
  x ^= x << 13;
  x ^= x >> 17;
  x ^= x << 5;
  return ((x < 0 ? -x : x) % 100000) / 100000;
}

/**
 * Параметри руху для спрайта: вид анімації, тривалість, зсув, амплітуда.
 *
 * Тварини одного двору мусять рухатись НЕЗАЛЕЖНО: інакше вони збиваються в
 * купу й виглядають «вкопаними» одна в одну. Тому фаза, доріжка й бік
 * рахуються від номера тварини, а не з випадкового шуму.
 */

export function motionFor(key: string, index: number): Motion {
  let seed = 7;
  for (let i = 0; i < key.length; i += 1) seed = seed * 31 + key.charCodeAt(i);
  // Номер тварини входить із КРОКОМ золотого перерізу, а не як seed += index * 977:
  // інакше сусідні тварини отримували майже однакові параметри.
  seed += index * 977;

  const kind = 'wander' as const;
  const slide = noise(seed + 4);
  const style = WALK_STYLE[key as HerdKey];

  /*
   * Фаза: сусідні тварини одного ряду мусять бути в ПРОТИФАЗІ, інакше вони
   * сходяться в одній точці двору й накладаються (замір: відстань падала до
   * 12px замість 36). Крок 1/2 замість золотого перерізу: тварина №0 іде
   * вперед, №1 — назад, №2 — знову вперед, і вони ніколи не збігаються.
   */
  const phase = (index % 2) / 2;
  /**
   * Початковий бік спрайта. Парні дивляться праворуч, непарні — ліворуч, щоб
   * у дворі не було однакових фігурок.
   */
  const flip = index % 2 === 0 ? '1' : '-1';

  /*
   * Темп «переступання» на місці. Від довжини циклу залежить швидкість, з якою
   * кадри змінюють один одного: качка дріботить, корова переступає повільно.
   * Множник 5 — навмисно неквапливо, щоб крок читався оком.
   */
  const cycle = (3.6 + slide * 4) * (style?.speed ?? 1) * 5;

  return {
    kind,
    vars: {
      /**
       * Час циклу кадрів. Крок (--walk-dur) = цикл / 6.5: у стрічці 6 кадрів,
       * і хода має встигати за темпом виду, а не дріботіти.
       */
      '--dur': `${cycle.toFixed(2)}s`,
      '--walk-dur': `${(cycle / 6.5).toFixed(2)}s`,
      // «Перевальцем» — легкий нахил у такт із кроком, без вертикального руху.
      '--waddle': `${style?.waddle ?? 2}deg`,
      // Негативна затримка — спрайт стартує посеред циклу, тому рухи не синхронні.
      '--delay': `-${(phase * 8).toFixed(2)}s`,
      '--flip': flip,
    },
  };
}
